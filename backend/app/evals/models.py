from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any

from app.db.models.message import Message
from app.db.models.tool_call import ToolCall
from app.services.tool_execution_service import ToolExecutionResult
from app.tools.types import (
    ToolExecutionStatus,
    ToolFailureType,
)


class EvalStatus(StrEnum):
    PASS = "pass"
    FAIL = "fail"
    ERROR = "error"


@dataclass(frozen=True)
class ExpectedToolCall:
    """
    Expected behavior for one tool call.

    Only arguments included here are checked. Other optional arguments
    generated by Gemini are allowed.
    """

    tool_name: str

    arguments: dict[str, Any] = field(
        default_factory=dict,
    )

    expected_status: ToolExecutionStatus = (
        ToolExecutionStatus.SUCCESS
    )

    expected_failure_type: ToolFailureType | None = None

    result_ticket_ids: set[int] | None = None


@dataclass(frozen=True)
class ExpectedTicketState:
    """
    Expected persisted state of one ticket after the eval.
    """

    ticket_id: int
    fields: dict[str, Any]


@dataclass(frozen=True)
class ExpectedCreatedTicket:
    """
    Expected ticket created during an eval.
    """

    lookup_subject: str
    fields: dict[str, Any]


@dataclass(frozen=True)
class EvalCase:
    """
    One fixed AI evaluation scenario.

    prompts contains one message for a normal case and multiple
    messages for a conversation-context case.
    """

    name: str
    description: str
    prompts: list[str]

    expected_tool_calls: list[ExpectedToolCall]

    allow_extra_tool_calls: bool = False

    expected_ticket_states: list[ExpectedTicketState] = field(
        default_factory=list,
    )

    expected_created_ticket: ExpectedCreatedTicket | None = None

    expected_ticket_count: int | None = None


@dataclass
class EvalObservation:
    """
    Actual behavior captured after all prompts in one eval case.
    """

    assistant_message: Message
    tool_executions: list[ToolExecutionResult]
    persisted_tool_calls: list[ToolCall]


@dataclass
class EvalResult:
    """
    Final result for one eval case.
    """

    case_name: str
    status: EvalStatus
    reasons: list[str] = field(default_factory=list)
    assistant_text: str | None = None
    duration_seconds: float | None = None